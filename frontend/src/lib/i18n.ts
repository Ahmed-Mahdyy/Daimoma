export type I18nKey = keyof (typeof dict)["en"];

/** gettext-style lookup: the argument is normally the English source
 * string, so untranslated keys fall back to English rather than breaking.
 * Namespaced keys (nav.*, shell.*, …) also resolve through the tables.
 * Params interpolate `{name}` placeholders. */
export function translate(
  lang: Language,
  key: string,
  params?: Record<string, string | number>,
): string {
  let out =
    (dict[lang] as Record<string, string>)[key] ??
    (dict.en as Record<string, string>)[key] ??
    key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}
